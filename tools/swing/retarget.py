"""Canonical mocap (data/<clip>.json + .shaft.json) -> src/golfer/swingclip.ts: per-frame channels the game rig reads.
Everything is proportion-free (angles, unit directions, ratios), so it scales to any body. Right-handed golfer in
character space (+X target, +Y up, +Z facing); the game mirrors the whole character for a lefty.
Usage: python3 -I retarget.py [clip=rory_faceon_clean]"""
import json, os, sys, numpy as np
from scipy.spatial.transform import Rotation as Rot
HERE = os.path.dirname(os.path.abspath(__file__)); clip = sys.argv[1] if len(sys.argv) > 1 else 'rory_faceon_clean'
D = json.load(open(f'{HERE}/data/{clip}.json')); SH = json.load(open(f'{HERE}/data/{clip}.shaft.json'))
J = np.array(D['joints']); Q = np.array(D['rot_xyzw']); n = len(J); rest = np.array(D['rest_joints']); E = D['events']
R = Rot.from_quat(Q.reshape(-1, 4)).as_matrix().reshape(n, 22, 3, 3)
unit = lambda v: v / np.linalg.norm(v, axis=-1, keepdims=True)
# pelvis = Ry(turn) Rz(side) Rx(tilt); chest = Rz(side) Rx(tilt) Ry(turn)  (the rig's conventions)
hip = Rot.from_matrix(R[:, 0]).as_euler('YZX'); chest = Rot.from_matrix(R[:, 9]).as_euler('ZXY')
hipTurn, hipSide, hipTilt = np.unwrap(hip[:, 0]), hip[:, 1], hip[:, 2]
chestSide, chestTilt, chestTurn = chest[:, 0], chest[:, 1], np.unwrap(chest[:, 2])
L = lambda a, b: np.linalg.norm(rest[a] - rest[b])
leg = L(1, 4) + L(4, 7); armL = L(16, 18) + L(18, 20); armR = L(17, 19) + L(19, 21)
a0 = int(round(E['BA']))
pel = (J[:, 0] - J[a0, 0]) / leg
# fuse the views: a face-on camera sees the pelvis slide along the target line (x) and its height, but not its depth
# (z); take z from the down-the-line clip at the same swing events
S2 = json.load(open(f'{HERE}/data/vanzyl_dtl.json')); J2 = np.array(S2['joints']); r2 = np.array(S2['rest_joints'])
leg2 = np.linalg.norm(r2[1] - r2[4]) + np.linalg.norm(r2[4] - r2[7]); b0 = int(round(S2['events']['BA']))
evs = [e for e in D['event_names'] if E[e] is not None and S2['events'][e] is not None]
t2 = np.interp(np.arange(n), [E[e] for e in evs], [S2['events'][e] for e in evs])
pel[:, 2] = np.interp(t2, np.arange(len(J2)), (J2[:, 0, 2] - J2[b0, 0, 2]) / leg2)
dL = J[:, 20] - J[:, 16]; dR = J[:, 21] - J[:, 17]
extL = np.minimum(1, np.linalg.norm(dL, axis=1) / armL); extR = np.minimum(1, np.linalg.norm(dR, axis=1) / armR)
elbL = unit(J[:, 18] - J[:, 16]); elbR = unit(J[:, 19] - J[:, 17])
kneeL = unit(J[:, 4] - J[:, 1]); kneeR = unit(J[:, 5] - J[:, 2])
# trail heel: pitch of the trail foot (ankle -> toe base) beyond its address pitch, as the game's 0..1 heel value
# (the game lifts the heel by 1.35 * smoothstep(0.25, 1.08, heel) radians)
fv = J[:, 11] - J[:, 8]; pitch = np.arctan2(-fv[:, 1], np.linalg.norm(fv[:, [0, 2]], axis=1)); dp = np.maximum(0, pitch - pitch[a0])
def inv_smooth(y):
    y = np.clip(y, 0, 1); lo, hi = np.zeros_like(y), np.ones_like(y)
    for _ in range(30):
        m = (lo + hi) / 2; v = m * m * (3 - 2 * m); lo = np.where(v < y, m, lo); hi = np.where(v < y, hi, m)
    return (lo + hi) / 2
heel = np.where(dp < 0.04, 0, 0.25 + 0.83 * inv_smooth(dp / 1.35)); heel[:int(E['MD'])] = 0; heel = np.maximum.accumulate(heel)
headF = R[:, 15] @ np.array([0, 0, 1.0]); headF = unit(headF)
shaft = unit(np.array(SH['shaft_dir'])); w2w = unit(J[:, 21] - J[:, 20])
th = np.radians(np.array(D['lead_arm_angle_deg']))
# light temporal smoothing of the body channels (monocular jitter), none on the labelled shaft
def sm(a):
    a = np.asarray(a, float); b = a.copy(); b[1:-1] = 0.25 * a[:-2] + 0.5 * a[1:-1] + 0.25 * a[2:]; return b
cols = [('hipTurn', sm(hipTurn)), ('hipSide', sm(hipSide)), ('hipTilt', sm(hipTilt)), ('chestTurn', sm(chestTurn)), ('chestTilt', sm(chestTilt)),
        ('chestSide', sm(chestSide)), ('pelvis', sm(pel)), ('leadDir', unit(sm(unit(dL)))), ('leadExt', sm(extL)), ('leadElbow', unit(sm(elbL))),
        ('trailElbow', unit(sm(elbR))), ('trailDir', unit(sm(unit(dR)))), ('trailExt', sm(extR)), ('shaft', shaft), ('heel', sm(heel)),
        ('kneeL', unit(sm(kneeL))), ('kneeR', unit(sm(kneeR))), ('head', unit(sm(headF))), ('armAngle', th), ('wristLine', unit(sm(w2w)))]
layout = {}; off = 0; mats = []
for name, a in cols:
    a = np.asarray(a, float).reshape(n, -1); layout[name] = [off, a.shape[1]]; off += a.shape[1]; mats.append(a)
M = np.hstack(mats)
ev = {k: v for k, v in E.items() if v is not None}
out = f'{HERE}/../../src/golfer/swingclip.ts'
with open(out, 'w') as f:
    f.write(f"""// GENERATED by tools/swing/retarget.py — do not edit by hand.
// A real swing recovered in 3D from video: {clip} (GVHMR, SMPL-X body), club shaft from labelled video frames fused
// with the down-the-line clip. Right-handed golfer in character space (+X target, +Y up, +Z facing); the game mirrors
// the character for a left-hander. Angles in radians as the rig reads them; directions are unit vectors; pelvis is the
// move from address in leg lengths; leadExt/trailExt are shoulder-to-wrist distance over arm length.
export const SWING_CLIP = {{
  source: '{clip}',
  frames: {n},
  stride: {off},
  /** channel name -> [offset, size] in each frame's row */
  layout: {json.dumps(layout)} as Record<string, [number, number]>,
  /** the 12 swing events (Haddas et al.) + the finish, as (fractional) frame numbers */
  events: {json.dumps(ev)} as Record<'BA' | 'MB' | 'LBA' | 'LB' | 'EPR' | 'TB' | 'EDA' | 'ED' | 'MD' | 'BI' | 'MF' | 'LF' | 'FIN', number>,
  data: new Float32Array([
""")
    for r in M: f.write('    ' + ','.join(f'{v:.4f}'.rstrip('0').rstrip('.') if abs(v) > 5e-5 else '0' for v in r) + ',\n')
    f.write("  ]),\n};\n")
print('wrote', out, M.shape)
np.set_printoptions(precision=2, suppress=True, linewidth=200)
for k in ev:
    i = int(round(ev[k])); print(f'{k:4s} f{ev[k]:5.1f} hipTurn {hipTurn[i]-hipTurn[a0]:5.2f} chestTurn {chestTurn[i]-chestTurn[a0]:5.2f} chestTilt {chestTilt[i]:5.2f} chestSide {chestSide[i]:5.2f} hipTilt {hipTilt[i]:5.2f} pel {pel[i]} ext {extL[i]:.2f}/{extR[i]:.2f} heel {heel[i]:.2f}')
